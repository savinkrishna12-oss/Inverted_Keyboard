export function getRandomSentence(category = null) {
  let pool = SENTENCES;
  if (category && category !== 'All') {
    pool = SENTENCES.filter(s => s.category.toLowerCase() === category.toLowerCase());
    if (pool.length === 0) pool = SENTENCES;
  }
  return pool[Math.floor(Math.random() * pool.length)];
}

export function getBossSentence(level = 1) {
  const bosses = SENTENCES.filter(s => s.category === 'Impossible Mode');
  return bosses[(level - 1) % bosses.length] || bosses[0];
}

export function getMovieSentence() {
  const movieSentences = SENTENCES.filter(s => s.category === 'Fake Movie Quotes');
  return movieSentences[Math.floor(Math.random() * movieSentences.length)];
}


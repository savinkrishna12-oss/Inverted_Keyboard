/**
 * Injects a mathematical expression into a sentence either inline (at a comma/boundary)
 * or as an appendix formula.
 * @param {string} sentenceText 
 * @returns {string} mutated sentence with mathematical expressions
 */
export function injectMathExpressionIntoSentence(sentenceText) {
  if (!sentenceText || typeof sentenceText !== 'string') return sentenceText;

  // If sentence is already heavily mathematical (contains 3+ math operators), don't over-mutate
  const mathChars = (sentenceText.match(/[=+*^%<>/]/g) || []).length;
  if (mathChars >= 3) {
    return sentenceText;
  }

  const pickInline = Math.random() < 0.55;

  if (pickInline && sentenceText.includes(',')) {
    const inlineExp = MATH_EXPRESSIONS_INLINE[Math.floor(Math.random() * MATH_EXPRESSIONS_INLINE.length)];
    const commaIndex = sentenceText.indexOf(',');
    if (commaIndex !== -1) {
      const beforeComma = sentenceText.slice(0, commaIndex);
      const afterComma = sentenceText.slice(commaIndex + 1).trimStart();
      return `${beforeComma}${inlineExp} ${afterComma}`;
    }
  }

  // Appendix injection before trailing punctuation
  const appendix = MATH_EXPRESSIONS_APPENDIX[Math.floor(Math.random() * MATH_EXPRESSIONS_APPENDIX.length)];
  const trimmed = sentenceText.trim();
  if (trimmed.endsWith('.') || trimmed.endsWith('!') || trimmed.endsWith('?')) {
    const punct = trimmed.slice(-1);
    const body = trimmed.slice(0, -1);
    return `${body}${appendix}`;
  }

  return `${trimmed}${appendix}`;
}

